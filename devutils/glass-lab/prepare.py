#!/usr/bin/env python3
"""Extract native material implementations from their owned production patch."""
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parents[2]
lab = Path(__file__).resolve().parent
patch = root / 'patches/personal/arcium-surface-roles-macos.patch'


def additions(path):
    text = patch.read_text().split('Index: ' + path + '\n', 1)[1].split('\nIndex: ', 1)[0]
    return '\n'.join(line[1:] for line in text.splitlines()
                     if line.startswith('+') and not line.startswith('+++')) + '\n'


swift = additions('src/chrome/browser/ui/cocoa/arcium_settings_swift/Sources/ArciumSettingsUI/ArciumPublicGlass.swift')
native = additions('src/chrome/browser/ui/views/omnibox/arcium_command_bar_material_mac.mm')
material = native.split('// A panel\'s glass:', 1)[1].split('// Port of SettingsUI', 1)[0]
assert material.count('@interface ') == 1 and material.count('@implementation ') == 1
assert material.count('@end') == 2
appearance = native.split('// Port of SettingsUI', 1)[1].split('ForcedAppearance AppearanceFor(', 1)[0]
# Chromium supplies a process-lifetime holder. The standalone app needs only std.
appearance = appearance.replace('static base::NoDestructor<std::set<Class>> installed;',
                                'static auto* installed = new std::set<Class>();')
header = '''// Generated by prepare.py from the production macOS patch. Do not edit.
#import "GlassNative.h"
#import <QuartzCore/QuartzCore.h>
#include <objc/runtime.h>
#include <set>
namespace helium {
enum class PanelMaterial { kSolid, kFast, kLiquid, kSystemLiquid, kFrosted, kGlassmorphic };
}
@protocol NativeWindowBackgroundView @end
extern "C" void* ArciumPublicGlassCreate(double, double, double, double, double);
extern "C" void ArciumPublicGlassUpdate(void*, double, double, double, double, double);
namespace {
struct PublicLiquidBridge {
  decltype(&ArciumPublicGlassCreate) create = ArciumPublicGlassCreate;
  decltype(&ArciumPublicGlassUpdate) update = ArciumPublicGlassUpdate;
};
const PublicLiquidBridge& GetPublicLiquidBridge() {
  static PublicLiquidBridge bridge;
  return bridge;
}
}
// A panel's glass:'''
footer = '''
// AppKit can ask this private appearance query off the main thread, as noted
// in remote_cocoa's NativeWidgetMacNSWindow implementation. Keep the bridge
// in Objective-C so those calls never enter a Swift main-actor thunk.
@interface NSWindow (LabAppearanceQuery)
- (BOOL)hasKeyAppearance;
@end
@implementation LabHostPanel
- (BOOL)canBecomeKeyWindow { return YES; }
- (BOOL)canBecomeMainWindow { return NO; }
- (BOOL)hasKeyAppearance {
  if (!NSThread.isMainThread) {
    return [super hasKeyAppearance];
  }
  return NSApp.isActive &&
      (self.isKeyWindow || self.parentWindow.isKeyWindow || self.parentWindow.isMainWindow);
}
@end

NSView* LabCreateMaterialView() { return [[ArciumPanelMaterialView alloc] initWithFrame:NSZeroRect]; }
void LabApplyMaterial(NSView* view, int material, double red, double green,
                      double blue, double alpha, double radius) {
  [(ArciumPanelMaterialView*)view applyMaterial:static_cast<helium::PanelMaterial>(material)
      tint:[NSColor colorWithSRGBRed:red green:green blue:blue alpha:alpha] cornerRadius:radius];
}
void LabSetWindowAppearance(NSWindow* window, int appearance) {
  SetForcedAppearance(window, static_cast<ForcedAppearance>(appearance));
}
'''
outputs = {
    lab / 'Sources/ArciumGlassLab/ProductionGlass.swift': swift,
    lab / 'Sources/GlassNative/ProductionMaterial.mm': header + material + '// Port of SettingsUI' + appearance + footer,
}
for path, content in outputs.items():
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)
print('Native renderer source: ' + hashlib.sha256(patch.read_bytes()).hexdigest()[:12])

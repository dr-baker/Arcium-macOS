"""Command-line entry used by dev.sh: python3 -m he <command> ..."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import plistlib
import shutil
import subprocess
import sys

from . import builds, catalog, lane, quilt, records, scratch, timestamps
from .common import HeError, Paths, make_paths, write_atomic
from .lock import run_locked

_GCLIENT = '''# Generated by he setup so depot_tools can find src/ outside a gclient
# checkout. Do not run gclient sync here.
solutions = [
  {
    "name": "src",
    "url": "https://chromium.googlesource.com/chromium/src.git",
    "managed": False,
    "custom_deps": {},
    "custom_vars": {},
  },
]
'''
_GCLIENT_ENTRIES = 'entries = {\n  "src": "https://chromium.googlesource.com/chromium/src.git",\n}\n'
# sccache appends /sccacheXXXXXX/sock; macOS Unix sockets allow 104 bytes.
_TMPDIR_LIMIT = 80


def problems(paths: Paths) -> list[str]:
    found = list(records.acquisition_problems(paths))
    if not (paths.catalog / catalog.MANIFEST).is_file():
        return found + ["no patch catalog; run he merge"]
    series = quilt.read_list(paths.catalog / "series.merged")
    applied = quilt.applied(paths.src)
    if applied != series[: len(applied)]:
        found.append("applied patches are not a prefix of series.merged; run he pop, then he push")
    elif len(applied) < len(series):
        found.append(f"{len(series) - len(applied)} of {len(series)} patches are not applied; run he push")
    found += catalog.drift(paths)
    found += [f"{name} was refreshed but not saved back; run he save-patch at that patch, or he unmerge"
              for name in catalog.unsaved(paths) if name not in applied]
    found += records.applied_drift(paths)
    for relative in quilt.owned_files(paths.src, applied):
        if (paths.src / f"{relative}.rej").exists():
            found.append(f"reject file left behind: {relative}.rej; fix the patch, then delete it")
    found += records.stamp_drift(paths)
    if (note := timestamps.status(paths)) is not None:
        found.append(note)
    return found


def _tmpdir(paths: Paths) -> str:
    explicit = os.environ.get("HELIUM_TMPDIR")
    if explicit:
        path = Path(explicit).expanduser()
    else:
        path = paths.state / "tmp"
        if len(os.fsencode(path)) > _TMPDIR_LIMIT:
            # A short per-user directory at the top of the build dir's volume.
            volume = paths.build_dir
            while volume.parent != volume and os.stat(volume.parent).st_dev == os.stat(volume).st_dev:
                volume = volume.parent
            tag = hashlib.sha256(str(paths.build_dir).encode()).hexdigest()[:8]
            path = volume / f".arcium-tmp-{os.getuid()}" / tag
    if len(os.fsencode(path)) > _TMPDIR_LIMIT:
        raise HeError(f"temp dir path is too long for sccache sockets: {path}; set HELIUM_TMPDIR to a shorter path")
    try:
        path.mkdir(mode=0o700, parents=True, exist_ok=True)
    except OSError as error:
        raise HeError(f"could not create temp dir {path} ({error.strerror}); set HELIUM_TMPDIR") from error
    return str(path)


def _free_gib(paths: Paths) -> float:
    """Free space for the build dir, counting a disk image's host volume."""
    path = paths.build_dir
    while not path.exists():
        path = path.parent
    free = shutil.disk_usage(path).free
    info = subprocess.run(["hdiutil", "info", "-plist"], capture_output=True, check=False)
    if info.returncode == 0:
        for image in plistlib.loads(info.stdout).get("images", []):
            mounts = [e.get("mount-point") for e in image.get("system-entities", []) if e.get("mount-point")]
            if any(str(path.resolve()).startswith(m.rstrip("/") + "/") or str(path.resolve()) == m for m in mounts):
                host = Path(image.get("image-path", "")).parent
                if host.exists():
                    free = min(free, shutil.disk_usage(host).free)
    return free / (1 << 30)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python3 -m he")
    parser.add_argument("--worktree", required=True)
    parser.add_argument("--build-dir", required=True)
    parser.add_argument("--build-mode", choices=builds.MODES,
                        default=os.environ.get("HELIUM_DEV_BUILD_MODE", "diagnostics"))
    commands = parser.add_subparsers(dest="command", required=True)
    lane.add_parser(commands)
    lock = commands.add_parser("lock")
    lock.add_argument("--label", required=True)
    lock.add_argument("argv", nargs=argparse.REMAINDER)
    merger = commands.add_parser("merge")
    merger.add_argument("--discard", action="store_true", help="drop lane patch edits that were not saved back")
    commands.add_parser("unmerge")
    save = commands.add_parser("save-patch")
    save.add_argument("--style", choices=("p1", "ab"))
    commands.add_parser("sync-applied")
    commands.add_parser("mark-before-push")
    check = commands.add_parser("check")
    check.add_argument("--warn", action="store_true", help="print problems to stderr and exit 0")
    check.add_argument("--json", action="store_true", help="print the build dir's full state as JSON")
    stamp = commands.add_parser("stamp")
    stamp.add_argument("name", choices=sorted(records.STAMP_INPUTS))
    acquisition = commands.add_parser("acquisition")
    acquisition.add_argument("action", choices=("record", "require", "source-mode"))
    acquisition.add_argument("--source-mode", default="lite")
    keeper = commands.add_parser("timestamps")
    keeper.add_argument("action", choices=("capture", "restore", "discard", "status"))
    keeper.add_argument("--reason", default="requested")
    scratch_parser = commands.add_parser("scratch")
    scratch_parser.add_argument("action", choices=("create", "remove", "is"))
    scratch_parser.add_argument("name", nargs="?")
    puller = commands.add_parser("scratch-pull")
    puller.add_argument("relatives", nargs="+")
    commands.add_parser("gclient-marker")
    commands.add_parser("tmpdir")
    finder = commands.add_parser("locate")
    finder.add_argument("--mode", choices=("auto", "text", "regex", "path", "glob"), default="auto")
    finder.add_argument("--ignore-case", action="store_true")
    finder.add_argument("--json", action="store_true")
    finder.add_argument("--limit", type=int, default=40)
    finder.add_argument("query")
    run = commands.add_parser("run")
    run.add_argument("--profile")
    run.add_argument("--new", action="store_true")
    run.add_argument("--labeled", action="store_true")
    run.add_argument("--seed-from")
    run.add_argument("--empty", action="store_true")
    run.add_argument("--json", action="store_true")
    run.add_argument("passthrough", nargs=argparse.REMAINDER)
    stop = commands.add_parser("stop")
    stop.add_argument("--profile")
    commands.add_parser("test-assets")
    completed = commands.add_parser("completed-build")
    completed.add_argument("targets", nargs="+")
    commands.add_parser("verify-build")
    commands.add_parser("configuration-current")
    guard = commands.add_parser("agent-guard")
    guard.add_argument("--edge-budget", type=int, default=None)
    guard.add_argument("--approved", action="store_true")
    guard.add_argument("targets", nargs="*")
    space = commands.add_parser("space")
    space.add_argument("--need-gib", type=float, required=True)
    args = parser.parse_args(argv)
    try:
        paths = make_paths(args.worktree, args.build_dir, args.build_mode)
        if args.command == "lock":
            command = args.argv[1:] if args.argv[:1] == ["--"] else args.argv
            return run_locked(paths.state / "lane.lock", command, label=args.label, worktree=paths.worktree)
        if args.command == "lane":
            return lane.main(paths, args)
        if args.command == "merge":
            records.require_compatible(paths)
            catalog.merge(paths, discard=args.discard)
            print(f"merged {len(quilt.read_list(paths.catalog / 'series.merged'))} patches into {paths.catalog}")
        elif args.command == "unmerge":
            for name in catalog.unmerge(paths):
                print(f"wrote {name}")
        elif args.command == "save-patch":
            print(f"saved {catalog.save_patch(paths, args.style)}")
        elif args.command == "sync-applied":
            records.sync_applied(paths)
        elif args.command == "mark-before-push":
            records.mark_before_push(paths)
        elif args.command == "check" and args.json:
            from . import agent
            found = problems(paths)
            print(agent.dumps(agent.status(paths, found)))
            return 1 if found else 0
        elif args.command == "check":
            found = problems(paths)
            for line in found:
                print(f"{'warning' if args.warn else 'problem'}: {line}", file=sys.stderr if args.warn else sys.stdout)
            if not found and not args.warn:
                print(f"ok: {len(quilt.applied(paths.src))} patches applied and current")
            return 0 if args.warn or not found else 1
        elif args.command == "stamp":
            records.record_stamp(paths, args.name)
        elif args.command == "completed-build":
            builds.record_completed(paths, args.targets)
        elif args.command == "verify-build":
            builds.require_completed(paths.out, paths.build_mode)
        elif args.command == "configuration-current":
            return 1 if (not (paths.out / "args.gn").is_file()
                         or records.stamp_drift(paths, ("gn-defaults",))) else 0
        elif args.command == "acquisition":
            if args.action == "record":
                records.record_acquisition(paths, args.source_mode)
            elif args.action == "require":
                records.require_compatible(paths)
            else:
                print(records.source_mode(paths) or "")
        elif args.command == "timestamps":
            action = {"capture": timestamps.capture, "restore": timestamps.restore, "status": timestamps.status,
                      "discard": lambda p: timestamps.discard(p, args.reason)}[args.action]
            if (message := action(paths)) is not None:
                print(message, file=sys.stderr)
        elif args.command == "scratch":
            if args.action == "is":
                return 0 if scratch.is_scratch(paths.build_dir) else 1
            if not args.name:
                parser.error("scratch create/remove needs a name")
            if args.action == "create":
                root = scratch.create(paths, args.name)
                print(root)
            else:
                print(f"removed {scratch.remove(paths, args.name)}")
        elif args.command == "scratch-pull":
            for relative in scratch.pull(paths, args.relatives):
                print(f"pulled {relative}")
        elif args.command == "gclient-marker":
            for name, content in ((".gclient", _GCLIENT), (".gclient_entries", _GCLIENT_ENTRIES)):
                if not (paths.build_dir / name).exists():
                    write_atomic(paths.build_dir / name, content.encode())
        elif args.command == "tmpdir":
            print(_tmpdir(paths))
        elif args.command == "locate":
            from . import locate
            report = locate.locate(paths.worktree, args.query, mode=args.mode, build_root=paths.build_dir,
                                   source=paths.src, limit=args.limit, ignore_case=args.ignore_case)
            print(json.dumps(report, indent=2, sort_keys=True) if args.json else locate.format_report(report))
        elif args.command == "run":
            from . import devapp
            extra = args.passthrough[1:] if args.passthrough[:1] == ["--"] else args.passthrough
            launched = devapp.run(paths, args.profile, new=args.new, labeled=args.labeled,
                                  seed=args.seed_from, empty=args.empty, passthrough=extra)
            print(devapp.describe(launched) if args.json else
                  f"running {Path(launched['app']).name} pid {launched['pid']} on {launched['profile']}\nlog: {launched['log']}")
        elif args.command == "stop":
            from . import devapp
            print(devapp.stop(args.profile))
        elif args.command == "test-assets":
            if records.source_mode(paths) == "full":
                from . import test_assets
                print(test_assets.ensure(paths.src), file=sys.stderr)
        elif args.command == "agent-guard":
            from . import agent
            budget = args.edge_budget if args.edge_budget is not None else int(
                os.environ.get("HELIUM_EDGE_BUDGET", agent.DEFAULT_EDGE_BUDGET))
            edges = agent.guard_build(paths, args.targets, budget=budget, approved=args.approved,
                                      problems=[p for p in problems(paths) if not p.startswith("timestamp snapshot")])
            print(edges)
        elif args.command == "space":
            free = _free_gib(paths)
            if free < args.need_gib:
                raise HeError(f"{free:.0f} GiB free for {paths.build_dir}; this needs {args.need_gib:.0f} GiB "
                              "(pass --force to continue anyway)")
    except HeError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
